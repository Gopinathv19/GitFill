import { describe, expect, it } from "vitest";
import { splitAnswer } from "@/lib/client/answer-parts";

const answer = [
  "### How booking works",
  "",
  "Main loops forever [`main.go:35-71`](https://github.com/a/b/blob/sha/main.go#L35-L71)[^C1]. Phone must be 10 digits [`helper.go:11`](https://x/h#L11)[^C2].",
  "",
  "**Sources**",
  "",
  "- [`main.go:35-71`](https://x/m) — main loop",
  "",
  "**Not verified in code**",
  "",
  "- Shutdown behaviour.",
  "",
  "**You could ask next**",
  "",
  "- Should the underflow bug be fixed?",
  "- Should history persist?",
  "",
  "[^C1]: **Verified** · [main.go:35-71](https://github.com/a/b/blob/sha/main.go#L35-L71) — Main loops forever.",
  "[^C2]: Unverified · `helper/helper.go:11` — Phone must be `len == 10`.",
  "",
  "",
  "---",
  "",
  "<sub>Explanation generated by GitFill from `a/b` @ `sha` (main). 2 claims recorded.</sub>",
  "",
].join("\n");

describe("splitAnswer", () => {
  it("separates body, evidence, sources, follow-ups and footer", () => {
    const parts = splitAnswer(answer);
    expect(parts.evidence).toEqual([
      { ref: "C1", n: 1, status: "verified", location: "main.go:35-71", href: "https://github.com/a/b/blob/sha/main.go#L35-L71", claim: "Main loops forever." },
      { ref: "C2", n: 2, status: "unverified", location: "helper/helper.go:11", href: null, claim: "Phone must be `len == 10`." },
    ]);
    expect(parts.sources).toBe("- [`main.go:35-71`](https://x/m) — main loop");
    expect(parts.followUps).toEqual(["Should the underflow bug be fixed?", "Should history persist?"]);
    expect(parts.footer).toBe("Explanation generated by GitFill from `a/b` @ `sha` (main). 2 claims recorded.");
    expect(parts.body).toContain("(https://github.com/a/b/blob/sha/main.go#L35-L71) [C1](#gf-ev-C1).");
    expect(parts.body).toContain("**Not verified in code**");
    expect(parts.body).not.toMatch(/Sources|You could ask next|\[\^C|<sub>|---/);
  });

  it("leaves plain replies untouched", () => {
    const parts = splitAnswer("Started the handbook. Progress appears below.");
    expect(parts).toMatchObject({ body: "Started the handbook. Progress appears below.", evidence: [], sources: null, followUps: [], footer: null });
  });

  it("reads the newer italic footer", () => {
    expect(splitAnswer("Answer.\n\n---\n\n*Explanation generated by GitFill from `a/b`.*\n").footer).toBe("Explanation generated by GitFill from `a/b`.");
  });
});
