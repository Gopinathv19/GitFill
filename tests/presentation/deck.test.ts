import { sampleDeck } from "@/tests/fixtures/sample-deck";

const ctx = { repoLabel: "acme/app · main", evidence: "evidence: acme/app @ abc1234", coverMeta: [["Repository", "acme/app"]] as Array<[string, string]> };
const pageCount = (html: string) => html.match(/<section class="page/g)?.length ?? 0;

describe("deck spec", () => {
  it("strips unknown claim refs at any depth and dangling diagram edges", () => {
    const spec: DeckSpec = structuredClone(sampleDeck);
    const page = spec.slides[3] as PageSlide;
    const diagram = page.main[0]!;
    if (diagram.type !== "diagram" || diagram.figure.kind !== "architecture") throw new Error("fixture changed");
    diagram.figure.edges.push({ from: "router", to: "ghost", style: "solid" });
    diagram.claimRefs = ["C1", "C99"];
    const { spec: out, issues } = normalizeDeckSpec(spec, new Set(["C1"]));
    expect(slideClaimRefs(out.slides[3]!)).toEqual(["C1"]);
    const fixed = (out.slides[3] as PageSlide).main[0]!;
    expect(fixed.type === "diagram" && fixed.figure.kind === "architecture" && fixed.figure.edges.some((e) => e.to === "ghost")).toBe(false);
    expect(issues.map((i) => i.message)).toEqual(expect.arrayContaining([expect.stringContaining("C99"), expect.stringContaining("edge")]));
  });

  it("removes numbering the author put in section names", () => {
    const spec: DeckSpec = structuredClone(sampleDeck);
    (spec.slides[3] as PageSlide).section = "02 · Architecture";
    const { spec: out } = normalizeDeckSpec(spec, new Set());
    expect((out.slides[3] as PageSlide).section).toBe("Architecture");
  });

  it("pads short table rows and trims long ones to the column count", () => {
    const page = pageSlide.parse({
      id: "s2",
      layout: "page",
      section: "Data",
      title: "Tables",
      main: [{ type: "table", columns: ["A", "B"], rows: [{ head: "x", cells: ["1"] }, { head: "y", cells: ["1", "2", "3"] }] }],
    });
    const spec = deckSpecSchema.parse({ ...sampleDeck, slides: [sampleDeck.slides[0], page] });
    const { spec: out } = normalizeDeckSpec(spec, new Set());
    const table = (out.slides[1] as PageSlide).main[0]!;
    expect(table.type === "table" && table.rows.map((r) => r.cells.length)).toEqual([2, 2]);
  });
});

describe("deck HTML", () => {
  const html = renderDeckHtml(sampleDeck, ctx);

  it("renders one fixed page per slide with the fonts embedded", () => {
    expect(pageCount(html)).toBe(sampleDeck.slides.length);
    expect(html).toContain("font/woff2;base64");
    expect(html).not.toMatch(/<link[^>]+stylesheet/);
  });

  it("numbers sections in order of first appearance and lists them on the contents page", () => {
    expect(sectionsOf(sampleDeck).map((s) => `${s.n} ${s.title} p${s.page}`)).toEqual([
      "01 Overview p3",
      "02 Architecture p4",
      "03 How it works p6",
      "04 Operations p9",
      "05 Reference p10",
    ]);
    expect(html).toContain('<span class="big-n">02</span>');
  });

  it("escapes text and allows only bold, code and the cover accent", () => {
    expect(inline("<script>x</script> **b** `c`")).toBe("&lt;script&gt;x&lt;/script&gt; <b>b</b> <code>c</code>");
    expect(inline("a *b*")).toBe("a *b*");
    expect(inline("a *b*", { accent: true })).toBe("a <em>b</em>");
  });

  it("keeps side blocks on a stacked page", () => {
    const page = { ...(sampleDeck.slides[2] as PageSlide), arrangement: "stack" as const };
    const out = renderDeckHtml({ ...sampleDeck, slides: [sampleDeck.slides[0]!, page] }, ctx);
    expect(out).toContain('data-block="side.0"');
    expect(out).toContain('class="pg-body arr-stack"');
  });

  it("shows exactly the given cover facts, not the model's own", () => {
    expect(html).toMatch(/Repository<b>acme\/app<\/b>/);
    expect(html).not.toContain("Gopinathv19/memora</b>");
    // "Generated by" is a label like any other now: shown only when the deck's labels list it.
    expect(html).not.toContain("Generated by<b>GitFill</b>");
  });
});

describe("diagrams", () => {
  it("wraps on word boundaries without dropping words", () => {
    expect(wrap("one two three four five", 9, 2)).toEqual(["one two", "three four five"]);
    expect(wrap(undefined, 10)).toEqual([]);
  });

  it("lays out every figure kind as an SVG whose boxes can be checked", () => {
    for (const slide of sampleDeck.slides) {
      if (slide.layout !== "page") continue;
      for (const b of [...slide.main, ...slide.side]) {
        if (b.type !== "diagram") continue;
        const svg = renderFigure(b.figure);
        expect(svg).toMatch(/^<svg viewBox="0 0 [\d.]+ [\d.]+"/);
        expect(svg).toContain('<g class="n');
      }
    }
  });

  it("runs a flow left to right in a wide column and top to bottom in a narrow one", () => {
    const flow = (sampleDeck.slides[5] as PageSlide).main[0]!;
    if (flow.type !== "diagram") throw new Error("fixture changed");
    const size = (svg: string) => svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)!.slice(1).map(Number);
    const [ww, wh] = size(renderFigure(flow.figure, 1180));
    const [nw, nh] = size(renderFigure(flow.figure, 600));
    expect(ww / wh).toBeGreaterThan(2);
    expect(nw / nh).toBeLessThan(2);
  });
});

describe("legacy specs", () => {
  it("converts a one-layout-per-slide deck into pages of blocks", () => {
    const spec = parseDeckSpec({
      title: "Old deck",
      audience: "Engineers",
      purpose: "Explain",
      theme: "midnight",
      slides: [
        { id: "s1", layout: "title", title: "Old deck", subtitle: "Overview", meta: "acme/app · main · abc1234 and a long tail beyond thirty characters", claimRefs: [] },
        { id: "s2", layout: "bullets", title: "Points", keyMessage: "The key point.", bullets: [{ text: "One", claimRefs: ["C1"] }, { text: "Two", claimRefs: [] }], notes: "", claimRefs: [] },
        {
          id: "s3",
          layout: "architecture",
          title: "Map",
          nodes: [
            { id: "web", label: "Web", tier: 0 },
            { id: "db", label: "DB", tier: 3, detail: "Postgres" },
          ],
          edges: [{ from: "web", to: "db", label: "SQL" }],
          notes: "",
          claimRefs: [],
        },
        { id: "s4", layout: "metrics", title: "Numbers", metrics: [{ value: "12", label: "Services", claimRefs: [] }], bullets: [], notes: "", claimRefs: [] },
      ],
    });
    expect(spec.format).toBe(2);
    expect(spec.slides.map((s) => s.layout)).toEqual(["cover", "page", "page", "page"]);
    const points = spec.slides[1] as PageSlide;
    expect(points.main.map((b) => b.type)).toEqual(["list", "callout"]);
    expect(slideClaimRefs(points)).toEqual(["C1"]);
    // A single metric is below the stats minimum, so it becomes a callout.
    expect((spec.slides[3] as PageSlide).main[0]!.type).toBe("callout");
  });

  it("passes current specs through unchanged", () => {
    expect(parseDeckSpec(sampleDeck)).toEqual(sampleDeck);
  });
});

describe("deterministic repairs", () => {
  const issue = (code: string, message = ""): SlideIssue => ({ slideId: "s6", slideIndex: 5, source: "render", code, severity: "high", message });

  it("gives a cramped diagram the full width before anything else", () => {
    const fixed = repairDeterministically(sampleDeck.slides[5]!, [issue("diagram_small")]);
    expect(fixed?.slide.layout === "page" && fixed.slide.arrangement).toBe("stack");
  });

  it("tightens spacing for a small overflow, but leaves a large one to the model", () => {
    const small = repairDeterministically(sampleDeck.slides[2]!, [issue("overflow", "Content overflows the page by 40px")]);
    expect(small?.slide.layout === "page" && small.slide.density).toBe("compact");
    expect(repairDeterministically(sampleDeck.slides[2]!, [issue("overflow", "Content overflows the page by 300px")])).toBeNull();
    expect(repairDeterministically(sampleDeck.slides[2]!, [issue("underfilled")])).toBeNull();
  });
});

const hasChromium = (() => {
  try {
    return Boolean(process.env.CHROMIUM_PATH) || existsSync(chromium.executablePath());
  } catch {
    return false;
  }
})();

describe.skipIf(!hasChromium)("browser render", () => {
  afterAll(() => closeBrowser());

  it("renders every page, measures it, and finds no overflow or clipped diagram text in the sample deck", async () => {
    const dir = await mkdtemp(path.join(tmpdir(), "gitfill-deck-"));
    try {
      const r = await renderPages(renderDeckHtml(sampleDeck, ctx), dir);
      expect(r.slides).toHaveLength(sampleDeck.slides.length);
      expect(existsSync(r.pdfPath)).toBe(true);
      const issues = checkRender(sampleDeck, r.slides).filter((i) => i.code !== "underfilled");
      expect(issues).toEqual([]);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it("reports content that does not fit the page", async () => {
    const page = pageSlide.parse({
      id: "s2",
      layout: "page",
      section: "Overflow",
      title: "Too much",
      arrangement: "stack",
      main: [
        { type: "list", title: "Long", items: Array.from({ length: 7 }, (_, i) => ({ text: `Point ${i} ${"word ".repeat(36)}` })) },
        { type: "list", title: "Longer", items: Array.from({ length: 7 }, (_, i) => ({ text: `Point ${i} ${"word ".repeat(36)}` })) },
      ],
    });
    const spec = deckSpecSchema.parse({ ...sampleDeck, slides: [sampleDeck.slides[0], page] });
    const dir = await mkdtemp(path.join(tmpdir(), "gitfill-deck-"));
    try {
      const r = await renderPages(renderDeckHtml(spec, ctx), dir, { pdf: false });
      expect(checkRender(spec, r.slides).map((i) => i.code)).toContain("overflow");
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
});
