import { describe, expect, it } from "vitest";
import { renderDeckHtml } from "@/lib/presentation/html/render";
import { defaultLabels, withLabels } from "@/lib/presentation/labels";
import { sampleDeck } from "../fixtures/sample-deck";

const repo = { repository: "acme/app", branch: "main", sha: "abc1234def5678" };

describe("deck labels", () => {
  it("defaults to repository, commit, audience and GitFill", () => {
    const labels = defaultLabels({ ...sampleDeck, slides: [] }, repo);
    expect(labels.header).toBe("acme/app · main");
    expect(labels.footer).toBe("evidence: acme/app @ abc1234");
    expect(labels.cover.map((m) => m.label)).toEqual(["Repository", "Commit", "Audience", "Generated by"]);
  });

  it("keeps the legacy hidden commit as a branch fact", () => {
    const labels = defaultLabels({ ...sampleDeck, showCommit: false, slides: [] }, repo);
    expect(labels.footer).toBe("evidence: acme/app");
    expect(labels.cover[1]).toEqual({ label: "Branch", value: "main" });
  });

  it("keeps labels a deck already has", () => {
    const labels = { header: "", footer: "", cover: [{ label: "Repository", value: "acme/app" }] };
    expect(withLabels({ ...sampleDeck, labels }, repo).spec.labels).toBe(labels);
  });

  it("renders exactly the labels: a removed fact stays removed and empty header/footer text is hidden", () => {
    const labels = { header: "", footer: "", cover: [{ label: "Repository", value: "acme/app" }, { label: "Audience", value: "Judges" }] };
    const { spec, render } = withLabels({ ...sampleDeck, labels }, repo);
    const html = renderDeckHtml(spec, { repoLabel: render.repoLabel, evidence: render.evidenceLabel, coverMeta: render.coverMeta });
    const cover = html.slice(html.indexOf('class="cover-meta"'), html.indexOf("</section>", html.indexOf('class="cover-meta"')));
    expect(cover).toContain("Judges");
    expect(cover).not.toMatch(/Branch|Commit|Generated by/);
    expect(html).not.toContain("acme/app · main");
    expect(html).not.toContain("evidence:");
  });
});
