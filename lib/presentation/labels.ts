import type { DeckSpec } from "./spec";

export type DeckLabels = NonNullable<DeckSpec["labels"]>;

/**
 * Labels for a deck built from a repository: repository, branch and commit, audience, any facts the
 * cover slide itself lists, and GitFill. After this, the labels alone decide the cover's fact row.
 */
export function defaultLabels(spec: Pick<DeckSpec, "showCommit" | "audience" | "slides">, repo: { repository: string; branch: string; sha: string }): DeckLabels {
  const commit = repo.sha.slice(0, 7);
  const fixed = [
    { label: "Repository", value: repo.repository },
    spec.showCommit ? { label: "Commit", value: `${repo.branch} · ${commit}` } : { label: "Branch", value: repo.branch },
    { label: "Audience", value: spec.audience },
  ];
  const cover = spec.slides.find((s) => s.layout === "cover");
  const taken = new Set([...fixed.map((m) => m.label.toLowerCase()), "generated by"]);
  const extra = (cover?.layout === "cover" ? cover.meta : []).filter((m) => !taken.has(m.label.toLowerCase()));
  return {
    header: `${repo.repository} · ${repo.branch}`,
    footer: spec.showCommit ? `evidence: ${repo.repository} @ ${commit}` : `evidence: ${repo.repository}`,
    cover: [...fixed, ...extra, { label: "Generated by", value: "GitFill" }].slice(0, 5),
  };
}

/** The spec with its labels filled in (kept when already set), and the render options they map to. */
export function withLabels(spec: DeckSpec, repo: { repository: string; branch: string; sha: string }) {
  const labels = spec.labels ?? defaultLabels(spec, repo);
  return {
    spec: { ...spec, labels },
    render: { repoLabel: labels.header, evidenceLabel: labels.footer, coverMeta: labels.cover.map((m) => [m.label, m.value] as [string, string]) },
  };
}
