import type { MuseClient } from "@/lib/ai/client";
import { modelFor } from "@/lib/ai/models";
import { README_SYSTEM_PROMPT } from "@/lib/ai/prompts";
import type { RepositoryAnalysis } from "@/lib/agent/analysis-schema";
import { renderClaimsForPrompt } from "@/lib/agent/planner";
import type { RunRecorder } from "@/lib/agent/recorder";
import type { SourceSnapshot } from "@/lib/connectors/types";
import { checkMermaidSyntax } from "@/lib/analysis/mermaid";
import type { Claim } from "@/lib/evidence/evidence";

export interface ReadmeResult {
  markdown: string;
  /** Backticked paths in the README that do not exist in the repository tree. */
  unknownPaths: string[];
  /** Image links that pointed at files not in the repository; they were removed. */
  removedImages: string[];
}

/**
 * Muse Spark writes README.md from the analysis; code then checks every referenced
 * path against the real tree and flags any that do not exist.
 */
export async function generateReadme(opts: {
  client: MuseClient;
  snapshot: SourceSnapshot;
  analysis: RepositoryAnalysis;
  claims: Claim[];
  recorder: RunRecorder;
  /** The team's .gitfill folder as prompt text (describeGitfill). */
  gitfill?: string;
  /** The README in the repository now, to update rather than replace. */
  current?: string;
  instructions?: string;
}): Promise<ReadmeResult> {
  const event = await opts.recorder.start("step", "generate_readme", { repository: opts.snapshot.displayName }, modelFor("writer"));
  try {
    const res = await opts.client.chat({
      model: modelFor("writer"),
      purpose: "generate_readme",
      maxTokens: 8000,
      messages: [
        { role: "system", content: README_SYSTEM_PROMPT },
        {
          role: "user",
          content: [
            `Repository: ${opts.snapshot.displayName} (commit ${opts.snapshot.version.slice(0, 7)})`,
            opts.instructions ? `What the team asked for: ${opts.instructions}` : "",
            `Top-level paths:\n${topLevel(opts.snapshot).join("\n")}`,
            opts.gitfill ?? "",
            opts.current ? `<current_readme>\n${opts.current.slice(0, 40_000)}\n</current_readme>` : "",
            `Analysis:\n${JSON.stringify(opts.analysis)}`,
            `Claims:\n${renderClaimsForPrompt(opts.claims.filter((c) => c.status !== "unverified"))}`,
          ]
            .filter(Boolean)
            .join("\n\n"),
        },
      ],
    });
    await opts.recorder.addUsage(res.usage.inputTokens, res.usage.outputTokens);
    const raw = (res.message.content ?? "").trim().replace(/^```(?:markdown|md)?\n([\s\S]*)\n```$/, "$1");
    const { markdown: imagesChecked, removed: removedImages } = dropMissingImages(raw, opts.snapshot);
    const { markdown: checked, dropped: droppedDiagrams } = demoteBrokenDiagrams(imagesChecked);
    let markdown = checked;
    const unknownPaths = findUnknownPaths(markdown, opts.snapshot);
    markdown += `\n\n---\n\n<sub>Generated by GitFill from \`${opts.snapshot.displayName}\` at commit \`${opts.snapshot.version.slice(0, 7)}\`.${
      unknownPaths.length ? ` Unverified paths: ${unknownPaths.map((p) => `\`${p}\``).join(", ")}.` : ""
    }</sub>\n`;
    await event.succeed({ characters: markdown.length, unknownPaths, removedImages, droppedDiagrams });
    return { markdown, unknownPaths, removedImages };
  } catch (err) {
    await event.fail(err instanceof Error ? err.message : "README generation failed");
    throw err;
  }
}

/**
 * Mermaid blocks the model wrote that fail the syntax check become plain code blocks, so GitHub and
 * GitFill show their text instead of a "Syntax error" graphic.
 */
export function demoteBrokenDiagrams(markdown: string): { markdown: string; dropped: number } {
  let dropped = 0;
  const out = markdown.replace(/```mermaid\n([\s\S]*?)```/g, (block, body: string) => {
    if (!checkMermaidSyntax(body.trim()).length) return block;
    dropped++;
    return `\`\`\`text\n${body}\`\`\``;
  });
  return { markdown: out, dropped };
}

/**
 * Removes image links to repository files that do not exist (Markdown `![alt](path)` and HTML
 * `<img src="path">`); external https images are kept. A README never ships a broken picture.
 */
export function dropMissingImages(markdown: string, snapshot: Pick<SourceSnapshot, "inventory">): { markdown: string; removed: string[] } {
  const paths = new Set(snapshot.inventory.map((i) => i.path));
  const removed: string[] = [];
  const missing = (src: string) => {
    if (/^(https?:|data:)/i.test(src)) return false;
    const path = src.replace(/^\.\//, "").split(/[?#]/)[0]!;
    let decoded = path;
    try {
      decoded = decodeURI(path);
    } catch {
      // A malformed escape such as "100%.png": compare the path as written.
    }
    if (paths.has(path) || paths.has(decoded)) return false;
    removed.push(src);
    return true;
  };
  const out = markdown
    .replace(/!\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+"[^"]*")?\s*\)/g, (m, src: string) => (missing(src) ? "" : m))
    .replace(/<img\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi, (m, src: string) => (missing(src) ? "" : m))
    .replace(/\n{3,}/g, "\n\n");
  return { markdown: out, removed };
}

function topLevel(snapshot: SourceSnapshot): string[] {
  const dirs = new Set<string>();
  for (const i of snapshot.inventory) dirs.add(i.path.includes("/") ? `${i.path.split("/")[0]}/` : i.path);
  return [...dirs].sort().slice(0, 80);
}

/** Backticked tokens that look like repository paths but are absent from the tree. */
export function findUnknownPaths(markdown: string, snapshot: Pick<SourceSnapshot, "inventory">): string[] {
  const paths = new Set(snapshot.inventory.map((i) => i.path));
  const dirs = new Set<string>();
  for (const p of paths) {
    const parts = p.split("/");
    for (let i = 1; i < parts.length; i++) dirs.add(parts.slice(0, i).join("/"));
  }
  const unknown = new Set<string>();
  for (const m of markdown.matchAll(/`([^`\s]+)`/g)) {
    const token = m[1]!.replace(/^\.\//, "").replace(/\/$/, "");
    const looksLikePath = /^[\w.@-]+(\/[\w.@\[\]()-]+)+$/.test(token) || /^[\w-]+\.(ts|tsx|js|jsx|py|go|rs|json|ya?ml|toml|md|sql|prisma)$/.test(token);
    if (looksLikePath && !paths.has(token) && !dirs.has(token)) unknown.add(token);
  }
  return [...unknown];
}
