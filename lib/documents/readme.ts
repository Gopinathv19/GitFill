import type { MuseClient } from "@/lib/ai/client";
import { modelFor } from "@/lib/ai/models";
import { README_SYSTEM_PROMPT } from "@/lib/ai/prompts";
import type { RepositoryAnalysis } from "@/lib/agent/analysis-schema";
import { renderClaimsForPrompt } from "@/lib/agent/planner";
import type { RunRecorder } from "@/lib/agent/recorder";
import type { SourceSnapshot } from "@/lib/connectors/types";
import type { Claim } from "@/lib/evidence/evidence";

export interface ReadmeResult {
  markdown: string;
  /** Backticked paths in the README that do not exist in the repository tree. */
  unknownPaths: string[];
}

/**
 * Muse Spark writes README.md from the analysis; code then checks every referenced
 * path against the real tree and flags any that do not exist.
 */
export async function generateReadme(opts: {
  client: MuseClient;
  snapshot: SourceSnapshot;
  analysis: RepositoryAnalysis;
  claims: Claim[];
  recorder: RunRecorder;
}): Promise<ReadmeResult> {
  const event = await opts.recorder.start("step", "generate_readme", { repository: opts.snapshot.displayName }, modelFor("writer"));
  try {
    const res = await opts.client.chat({
      model: modelFor("writer"),
      purpose: "generate_readme",
      maxTokens: 8000,
      messages: [
        { role: "system", content: README_SYSTEM_PROMPT },
        {
          role: "user",
          content: `Repository: ${opts.snapshot.displayName} (commit ${opts.snapshot.version.slice(0, 7)})\n\nTop-level paths:\n${topLevel(opts.snapshot).join("\n")}\n\nAnalysis:\n${JSON.stringify(opts.analysis)}\n\nClaims:\n${renderClaimsForPrompt(opts.claims.filter((c) => c.status !== "unverified"))}`,
        },
      ],
    });
    await opts.recorder.addUsage(res.usage.inputTokens, res.usage.outputTokens);
    let markdown = (res.message.content ?? "").trim().replace(/^```(?:markdown|md)?\n([\s\S]*)\n```$/, "$1");
    const unknownPaths = findUnknownPaths(markdown, opts.snapshot);
    markdown += `\n\n---\n\n<sub>Generated by GitFill from \`${opts.snapshot.displayName}\` at commit \`${opts.snapshot.version.slice(0, 7)}\`.${
      unknownPaths.length ? ` Unverified paths: ${unknownPaths.map((p) => `\`${p}\``).join(", ")}.` : ""
    }</sub>\n`;
    await event.succeed({ characters: markdown.length, unknownPaths });
    return { markdown, unknownPaths };
  } catch (err) {
    await event.fail(err instanceof Error ? err.message : "README generation failed");
    throw err;
  }
}

function topLevel(snapshot: SourceSnapshot): string[] {
  const dirs = new Set<string>();
  for (const i of snapshot.inventory) dirs.add(i.path.includes("/") ? `${i.path.split("/")[0]}/` : i.path);
  return [...dirs].sort().slice(0, 80);
}

/** Backticked tokens that look like repository paths but are absent from the tree. */
export function findUnknownPaths(markdown: string, snapshot: Pick<SourceSnapshot, "inventory">): string[] {
  const paths = new Set(snapshot.inventory.map((i) => i.path));
  const dirs = new Set<string>();
  for (const p of paths) {
    const parts = p.split("/");
    for (let i = 1; i < parts.length; i++) dirs.add(parts.slice(0, i).join("/"));
  }
  const unknown = new Set<string>();
  for (const m of markdown.matchAll(/`([^`\s]+)`/g)) {
    const token = m[1]!.replace(/^\.\//, "").replace(/\/$/, "");
    const looksLikePath = /^[\w.@-]+(\/[\w.@\[\]()-]+)+$/.test(token) || /^[\w-]+\.(ts|tsx|js|jsx|py|go|rs|json|ya?ml|toml|md|sql|prisma)$/.test(token);
    if (looksLikePath && !paths.has(token) && !dirs.has(token)) unknown.add(token);
  }
  return [...unknown];
}
