import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "@/lib/config/env";

/**
 * The stored bytes for a key are gone (storage directory cleared, or the database points at a
 * machine that never held the file). Callers turn this into a 404 instead of a 500.
 */
export class ArtifactMissingError extends Error {
  override name = "ArtifactMissingError";
  constructor(readonly key: string) {
    super(`Stored file is no longer available: ${key}`);
  }
}

/**
 * Artifact storage. Local disk today; a Cloud Storage implementation can replace it
 * behind the same interface. Keys are generated by the app, never taken from users.
 */
export interface ArtifactStorage {
  put(key: string, data: Buffer): Promise<{ key: string; sizeBytes: number }>;
  /** Reads the stored bytes. Throws ArtifactMissingError when the file is gone. */
  get(key: string): Promise<Buffer>;
  /** True when the key still has bytes behind it. */
  exists(key: string): Promise<boolean>;
  /** Absolute local path for tools (Chromium, PptxGenJS) that need a file on disk. */
  localPath(key: string): string;
}

const KEY_RE = /^[a-zA-Z0-9][a-zA-Z0-9._-]*(\/[a-zA-Z0-9][a-zA-Z0-9._-]*)*$/;

export class LocalStorage implements ArtifactStorage {
  private readonly root: string;

  constructor(root = env().ARTIFACT_STORAGE_PATH) {
    this.root = path.resolve(root);
  }

  localPath(key: string): string {
    if (!KEY_RE.test(key) || key.includes("..")) throw new Error(`Invalid storage key: ${key}`);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep)) throw new Error("Storage key escapes storage root.");
    return full;
  }

  async put(key: string, data: Buffer) {
    const full = this.localPath(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, data);
    return { key, sizeBytes: data.byteLength };
  }

  async get(key: string) {
    try {
      return await readFile(this.localPath(key));
    } catch (err) {
      // The row survives in the database when the storage directory is cleared or when the
      // worker that wrote it ran elsewhere: report it as missing, not as a crash.
      if (isMissingFile(err)) throw new ArtifactMissingError(key);
      throw err;
    }
  }

  async exists(key: string) {
    try {
      await stat(this.localPath(key));
      return true;
    } catch (err) {
      if (isMissingFile(err)) return false;
      throw err;
    }
  }

  async size(key: string) {
    try {
      return (await stat(this.localPath(key))).size;
    } catch (err) {
      if (isMissingFile(err)) throw new ArtifactMissingError(key);
      throw err;
    }
  }
}

function isMissingFile(err: unknown): boolean {
  const code = (err as NodeJS.ErrnoException | null)?.code;
  return code === "ENOENT" || code === "ENOTDIR";
}

let instance: LocalStorage | undefined;
export function getStorage(): LocalStorage {
  instance ??= new LocalStorage();
  return instance;
}

/** Filename safe for Content-Disposition, derived from app data (e.g. repo name). */
export function safeFilename(base: string, ext: string): string {
  const clean = base.normalize("NFKD").replace(/[^a-zA-Z0-9._-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80) || "gitfill";
  return `${clean}.${ext}`;
}
