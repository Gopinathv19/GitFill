/**
 * Splits a rendered GitFill answer (see lib/understanding/render.ts) into what the chat shows
 * separately: the answer itself, the evidence footnotes, key source files, follow-up questions and
 * the provenance footer. Works on stored message text, so older messages get the same treatment.
 */

export type EvidenceStatus = "verified" | "inferred" | "unverified";

export interface EvidenceItem {
  ref: string;
  /** 1-based position, the number shown on the inline chip. */
  n: number;
  status: EvidenceStatus;
  location: string | null;
  href: string | null;
  claim: string;
}

export interface AnswerParts {
  /** Answer Markdown with footnote markers turned into `#gf-ev-<ref>` links. */
  body: string;
  evidence: EvidenceItem[];
  /** Markdown list of the key source files, if the answer had one. */
  sources: string | null;
  followUps: string[];
  footer: string | null;
}

const FOOTNOTE = /^\[\^([\w-]+)\]:\s*(\*\*Verified\*\*|\*Inferred\*|Unverified)\s*·\s*(.*?)\s+—\s+(.*)$/;
const FOOTER = /\n*^-{3,}[ \t]*\n+[ \t]*(?:<sub>([\s\S]*?)<\/sub>|\*([^*\n][^\n]*generated by GitFill[^\n]*)\*)[ \t]*\n?\s*$/m;

export const EVIDENCE_HREF = "#gf-ev-";

/** Gives every footnote ref in `markdown` a suffix (`[^C1]` → `[^C1-2]`), definitions included. */
export function suffixFootnotes(markdown: string, suffix: string): string {
  return markdown.replace(/\[\^([\w-]+)\]/g, (_, ref: string) => `[^${ref}-${suffix}]`);
}

/**
 * A chat reply can hold several answers (one per repository), each numbering its evidence from
 * C1. Footnote refs must be unique within a message, so every answer after the first gets its
 * refs suffixed. An answer ends where its footnote definitions end; the next body line starts
 * the next answer. Messages that are already unique come back unchanged.
 */
export function uniqueFootnotes(markdown: string): string {
  const lines = markdown.split("\n");
  const defs = lines.map((l) => /^\[\^([\w-]+)\]:/.exec(l)?.[1] ?? null);
  const all = defs.filter((d): d is string => d !== null);
  if (new Set(all).size === all.length) return markdown;
  let segment = 0;
  let seenDefs = false;
  return lines
    .map((line, i) => {
      if (defs[i]) seenDefs = true;
      else if (seenDefs && line.trim()) {
        segment++;
        seenDefs = false;
      }
      return segment ? suffixFootnotes(line, String(segment + 1)) : line;
    })
    .join("\n");
}

/** A "**Title**" line followed by a markdown list; group 1 is the leading newline, group 2 the list. */
const SOURCES_SECTION = /(^|\n)\*\*Sources\*\*[ \t]*\n+((?:[ \t]*[-*] .*(?:\n|$))+)/;
const FOLLOW_UPS_SECTION = /(^|\n)\*\*You could ask next\*\*[ \t]*\n+((?:[ \t]*[-*] .*(?:\n|$))+)/;

export function splitAnswer(markdown: string): AnswerParts {
  const evidence: EvidenceItem[] = [];
  const kept: string[] = [];
  for (const line of uniqueFootnotes(markdown).split("\n")) {
    const m = FOOTNOTE.exec(line);
    if (!m) {
      kept.push(line);
      continue;
    }
    const [, ref, status, where, claim] = m;
    const link = /^\[([^\]]+)\]\(([^)\s]+)\)$/.exec(where!.trim());
    const code = /^`([^`]+)`$/.exec(where!.trim());
    evidence.push({
      ref: ref!,
      n: evidence.length + 1,
      status: status === "**Verified**" ? "verified" : status === "*Inferred*" ? "inferred" : "unverified",
      location: link ? link[1]! : code ? code[1]! : where!.trim() === "no file" ? null : where!.trim(),
      href: link ? link[2]! : null,
      claim: claim!.trim(),
    });
  }

  let body = kept.join("\n");
  let footer: string | null = null;
  body = body.replace(FOOTER, (_, sub?: string, em?: string) => {
    footer = (sub ?? em ?? "").replace(/\s+/g, " ").trim();
    return "";
  });

  const sources = takeSection(SOURCES_SECTION);
  const followUps = (takeSection(FOLLOW_UPS_SECTION) ?? "")
    .split("\n")
    .map((l) => /^\s*[-*]\s+(.+)$/.exec(l)?.[1]?.trim())
    .filter((q): q is string => Boolean(q));

  // Footnote markers become links the renderer draws as status chips.
  const known = new Set(evidence.map((e) => e.ref));
  body = body.replace(/\[\^([\w-]+)\]/g, (whole, ref: string) => (known.has(ref) ? ` [${ref}](${EVIDENCE_HREF}${ref})` : whole));

  return { body: body.replace(/\n{3,}/g, "\n\n").trim(), evidence, sources, followUps, footer };

  /** Removes a "**Title**" block followed by a list, returning the list. */
  function takeSection(section: RegExp): string | null {
    let found: string | null = null;
    body = body.replace(section, (_, lead: string, list: string) => {
      found = list.trim();
      return lead;
    });
    return found;
  }
}
